#!/usr/bin/env python3
"""Regenerate the extension pages, and list them in the navigation.

Each extension has one body, in snippets/extensions/<slug>.mdx, and one thin
page at extensions/<slug>.mdx (en/extensions/ once English moves under en/)
that imports it. Every release shares that one
page. This script writes those pages and rewrites the extension list of
the Extensions tab (the group whose own page is the catalog), so adding an extension needs no hand edit of docs.json.
Run it after adding an extension or changing a See also list.

It refuses to run when the catalog in snippets/extensions-en.mdx and the
bodies in snippets/extensions/ name different sets of extensions, because that
mismatch otherwise ships as a catalog entry with no page behind it. It also
fails when it finds no catalog group to update, because a new page
that no menu lists is easy to miss.

Two Mintlify constraints shape this layout. Both were measured, and both look
like bugs in our own pages when they bite:

1. An .mdx snippet does NOT receive properties. Passing `slot="..."` into one
   and reading `{props.slot}` inside compiles, renders, and yields an empty
   string, so every link built that way becomes href="".

2. A relative link (../install) resolves correctly in the rendered page, but
   `mint broken-links` reads the snippet on its own, finds no such page, and
   exits 1. That check gates CI, so relative links are out too.

So the See also list lives in the generated page, as absolute links. In
scripts/extension-pages.json, `../<page>` names a page by its old stable name
and `vsql-<name>` names another extension; this script turns both into the
page's current address.

Usage:  python3 scripts/gen-extension-pages.py          # from the repo root
"""

import glob
import json
import os
import re
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(REPO, "scripts", "extension-pages.json")
DOCS_JSON = os.path.join(REPO, "docs.json")
CATALOG = os.path.join(REPO, "snippets", "extensions-en.mdx")
# English pages live under en/ once the site moves them there, and the 8.4
# version folder may drop its mysql- prefix (en/8.4/). The folder counts only
# when it holds pages: the old mysql-8.4/ folder keeps schema .json files.
EN = "en/" if glob.glob(os.path.join(REPO, "en", "**", "*.mdx"), recursive=True) else ""
V84 = "8.4" if glob.glob(os.path.join(REPO, EN, "8.4", "**", "*.mdx"), recursive=True) else "mysql-8.4"

GENERATED_NOTE = (
    "{/* Generated by scripts/gen-extension-pages.py. Edit the body in\n"
    "    snippets/extensions/<slug>.mdx, and the title, description, and\n"
    "    See also list in scripts/extension-pages.json, then re-run it.\n"
    "    See also is here, not in the snippet, because a snippet cannot take\n"
    "    a property and a relative link fails mint broken-links. */}"
)


def component_name(slug):
    return "".join(part.capitalize() for part in slug.split("-")) + "Page"


def current_addresses(docs):
    """Old stable page name -> current address, from the redirects docs.json keeps."""
    found = {}
    for r in docs.get("redirects", []):
        m = re.fullmatch(r"/(?:en/)?(?:mysql-)?8\.4/stable/([a-z0-9-]+)", r["source"])
        if m:
            found[m.group(1)] = r["destination"]
    return found


def resolve(item, addresses):
    def page(m):
        name = m.group(1)
        if name in addresses:
            return f"]({addresses[name]})"
        if os.path.exists(os.path.join(REPO, EN, V84, "stable", name + ".mdx")):
            return f"](/{EN}{V84}/stable/{name})"
        sys.exit(f"See also names ../{name}, and no page or redirect has that name")
    item = re.sub(r"\]\(\.\./([a-z0-9-]+)\)", page, item)
    item = re.sub(r"\]\((vsql-[a-z0-9-]+)\)", rf"](/{EN}extensions/\1)", item)
    return english_links(item)


def english_links(item):
    """Give an absolute link to an English page its /en prefix, when there is one."""
    if not EN:
        return item

    def prefix(m):
        top = re.split(r"[/#?]", m.group(1))[0]
        under_en = os.path.join(REPO, "en", top)
        if os.path.exists(under_en) or os.path.exists(under_en + ".mdx"):
            return f"](/en/{m.group(1)})"
        return m.group(0)
    return re.sub(r"\]\(/(?!en/)([^)\s]+)\)", prefix, item)


def catalog_slugs():
    """The extensions the catalog page lists, as page slugs."""
    heads = re.findall(r"^### (\S+)\s*$", open(CATALOG).read(), re.M)
    return {h.replace("_", "-") for h in heads}


def menu_order(slugs):
    """Menu order: the catalog's sections in order (core, community, example),
    alphabetical within each section."""
    section, rank = 0, {}
    for line in open(CATALOG):
        if line.startswith("## "):
            section += 1
        elif line.startswith("### "):
            rank[line[4:].strip().replace("_", "-")] = section
    return sorted(slugs, key=lambda s: (rank.get(s, section + 1), s))


def check_catalog(slugs):
    """Refuse to run when the catalog and the bodies disagree."""
    listed = catalog_slugs()
    missing_page = sorted(listed - set(slugs))
    missing_entry = sorted(set(slugs) - listed)
    if not missing_page and not missing_entry:
        return
    for slug in missing_page:
        print(f"catalog lists {slug} but snippets/extensions/{slug}.mdx does not exist")
    for slug in missing_entry:
        print(f"snippets/extensions/{slug}.mdx exists but the catalog does not list it")
    sys.exit("catalog and pages disagree; fix one of them and re-run")


LANGS = ["ja", "ko", "zh", "pt-BR"]
SEE_ALSO = {"en": "See also", "ja": "関連項目", "ko": "참고 항목", "zh": "另请参阅", "pt-BR": "Veja também"}


def localize(item, lang):
    """Point a resolved English link at the translated page when one exists."""
    def swap(m):
        path = m.group(1)
        rest = path[3:] if path.startswith("en/") else path
        page = rest.split("#")[0]
        if os.path.exists(os.path.join(REPO, lang, page + ".mdx")):
            return f"](/{lang}/{rest})"
        return m.group(0)
    return re.sub(r"\]\(/([^)\s]+)\)", swap, item)


def write_page(path, page, body, slug, see, heading):
    comp = component_name(slug)
    q = lambda v: json.dumps(v, ensure_ascii=False)
    open(path, "w").write(
        "---\n"
        f"title: {q(page['title'])}\n"
        f"sidebarTitle: {q(page['sidebar_title'])}\n"
        f"description: {q(page['description'])}\n"
        f"keywords: {q(page['keywords'])}\n"
        "audience: villagesql-user\n"
        "---\n\n"
        + GENERATED_NOTE.replace("<slug>", slug)
        + "\n\n"
        f'import {comp} from "/{body}";\n\n'
        f"<{comp} />\n\n"
        f"## {heading} {{#see-also}}\n\n" + see + "\n"
    )


def update_navigation(docs, slugs, translated):
    """Rewrite the extension list (the group whose own page is the catalog)
    of every Extensions tab. A
    translated menu lists its own pages, and only the ones that exist."""
    groups = []

    def walk(node):
        if isinstance(node, dict):
            if str(node.get("root", "")).endswith("extensions/catalog") and isinstance(node.get("pages"), list):
                groups.append(node)
            for value in node.values():
                walk(value)
        elif isinstance(node, list):
            for value in node:
                walk(value)

    for language in docs["navigation"]["languages"]:
        lang = language.get("language")
        before = len(groups)
        for tab in language.get("tabs", []):
            if tab.get("tab") == "Extensions":
                walk(tab)
        for group in groups[before:]:
            if lang == "en":
                group["pages"] = [f"{EN}extensions/{s}" for s in slugs]
            else:
                group["pages"] = [f"{lang}/extensions/{s}" for s in slugs if s in translated.get(lang, ())]
    if not groups:
        sys.exit("found no group whose own page is the catalog in an Extensions tab; the new pages would be in no menu")
    json.dump(docs, open(DOCS_JSON, "w"), indent=2, ensure_ascii=False)
    open(DOCS_JSON, "a").write("\n")
    return len(groups)


def main():
    data = json.load(open(DATA))
    docs = json.load(open(DOCS_JSON))
    check_catalog(sorted(data))
    addresses = current_addresses(docs)
    os.makedirs(os.path.join(REPO, EN, "extensions"), exist_ok=True)
    for slug, page in sorted(data.items()):
        body = f"snippets/extensions/{slug}.mdx"
        if not os.path.exists(os.path.join(REPO, body)):
            sys.exit(f"missing body: {body}")
        see = "\n".join(resolve(i, addresses) for i in page["see_also"])
        write_page(os.path.join(REPO, EN, "extensions", f"{slug}.mdx"), page, body, slug, see, SEE_ALSO["en"])

    # A translated page needs both its body and its data entry:
    # snippets/extensions/<lang>/<slug>.mdx and scripts/extension-pages.<lang>.json.
    translated = {}
    for lang in LANGS:
        data_path = os.path.join(REPO, "scripts", f"extension-pages.{lang}.json")
        if not os.path.exists(data_path):
            continue
        ldata = json.load(open(data_path))
        os.makedirs(os.path.join(REPO, lang, "extensions"), exist_ok=True)
        for slug, page in sorted(ldata.items()):
            body = f"snippets/extensions/{lang}/{slug}.mdx"
            if slug not in data or not os.path.exists(os.path.join(REPO, body)):
                sys.exit(f"{lang}: {slug} needs both {body} and an entry in extension-pages.{lang}.json")
            see = "\n".join(localize(resolve(i, addresses), lang) for i in page["see_also"])
            write_page(os.path.join(REPO, lang, "extensions", f"{slug}.mdx"), page, body, slug, see, SEE_ALSO[lang])
            translated.setdefault(lang, set()).add(slug)
    navs = update_navigation(docs, menu_order(data), translated)
    print(f"wrote {len(data)} extension pages, and translated pages: "
          + (", ".join(f"{l} {len(s)}" for l, s in sorted(translated.items())) or "none"))
    print(f"listed them in {navs} navigation groups")


if __name__ == "__main__":
    main()
